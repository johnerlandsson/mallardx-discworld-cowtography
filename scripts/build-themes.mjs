// Snapshot Mallard's bundled themes into ui/data/map-themes.js for the
// "Vector map theme" setting. Plugins can only see Mallard's *active* theme,
// so the other palettes are copied here at build time.
//
// Usage: npm run build:themes [-- <path to mallard repo or its themes dir>]
// Default source: $MALLARD_DIR or ~/dev/mallard.
//
// After running, update the [settings.map_theme] choices in plugin.toml if the
// theme list changed — scripts/build-themes.test.mjs fails until they match.

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { join, basename } from 'node:path'
import { homedir } from 'node:os'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'

// Same slot → index table as Mallard's src/composables/useTheme.ts.
const ANSI_SLOT_TO_INDEX = {
  black: 0, red: 1, green: 2, yellow: 3,
  blue: 4, magenta: 5, cyan: 6, white: 7,
  bright_black: 8, bright_red: 9, bright_green: 10, bright_yellow: 11,
  bright_blue: 12, bright_magenta: 13, bright_cyan: 14, bright_white: 15,
}

// Mirrors Mallard's panel_theme.rs safe_var_value: reject anything that could
// terminate a CSS declaration.
function safeValue(v) {
  return v.length > 0 && v.length <= 256 && !/[<>{};"'\\\n\r]/.test(v) && !v.includes('/*') && !v.includes('*/')
}

// Minimal parser for Mallard's flat theme TOML: top-level `key = "value"`
// pairs plus [colors] and [ansi] tables of the same shape.
export function parseThemeToml(raw) {
  let section = ''
  const top = {}, colors = {}, ansi = {}
  for (const line of raw.split(/\r?\n/)) {
    const t = line.trim()
    if (!t || t.startsWith('#')) continue
    const sec = t.match(/^\[([a-z_]+)\]$/)
    if (sec) { section = sec[1]; continue }
    const kv = t.match(/^([a-z_]+)\s*=\s*"([^"]*)"/)
    if (!kv) continue
    const [, k, v] = kv
    if (section === '') top[k] = v
    else if (section === 'colors') colors[k] = v
    else if (section === 'ansi') ansi[k] = v
  }
  const vars = {}
  for (const [k, v] of Object.entries(colors)) {
    if (safeValue(v)) vars[`--${k.replace(/_/g, '-')}`] = v
  }
  for (const [slot, v] of Object.entries(ansi)) {
    const idx = ANSI_SLOT_TO_INDEX[slot]
    if (idx !== undefined && safeValue(v)) vars[`--ansi-${idx}`] = v
  }
  return { name: top.name ?? '', base: top.base === 'light' ? 'light' : 'dark', vars }
}

export function renderModule(themes, source) {
  return `// Auto-generated by scripts/build-themes.mjs.
// Source: ${source}
// Do not edit by hand — re-run \`npm run build:themes\` to refresh.

export default ${JSON.stringify(themes, null, 2)};
`
}

function resolveThemesDir(arg) {
  const root = arg ?? process.env.MALLARD_DIR ?? join(homedir(), 'dev', 'mallard')
  const nested = join(root, 'src-tauri', 'themes')
  return existsSync(nested) ? nested : root
}

function main() {
  const dir = resolveThemesDir(process.argv[2])
  const files = readdirSync(dir).filter(f => f.endsWith('.toml'))
  if (files.length === 0) throw new Error(`no theme .toml files in ${dir}`)
  const parsed = files.map(f => [basename(f, '.toml'), parseThemeToml(readFileSync(join(dir, f), 'utf8'))])
  parsed.sort((a, b) => a[1].name.localeCompare(b[1].name))
  const themes = Object.fromEntries(parsed)
  const out = fileURLToPath(new URL('../ui/data/map-themes.js', import.meta.url))
  let rev = 'unknown commit'
  try { rev = execFileSync('git', ['-C', dir, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim() } catch {}
  writeFileSync(out, renderModule(themes, `Mallard src-tauri/themes/*.toml @ ${rev}`))
  console.log(`Wrote ${parsed.length} themes to ui/data/map-themes.js`)
  console.log('plugin.toml [settings.map_theme] choices:')
  console.log('  { value = "auto", label = "Follow Mallard" },')
  for (const [id, t] of parsed) console.log(`  { value = "${id}", label = "${t.name}" },`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main()
